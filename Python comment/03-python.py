# Single-line comments start with '#'; Python ignores them completely during execution.
print("Hello, World!")

# Placing '#' in front of code disables execution without deleting it (great for testing).
# print("Hello, World!")
print("Cheers, Mate!")

# Python lacks a dedicated multi-line comment tag, so you can stack multiple '#' lines.
# This is a comment written
# across more than one line.
print("Hello, World!")

# Unassigned triple quotes (""" """) are treated as multi-line comments or docstrings.
"""
This is a comment
written in more than one line.
"""
print("Hello, World!")
